	// if the current x coordinate is higher than the max allowed the program stops
		cmp r5, #79
		bgt end			
	// if the current x coordinate is lower than the max allowed the program stops
		cmp r5, #0
		blt end
//if there is a letter, then it should be printed by the main body of the program
		cmp r9, #0
		bne body_print
	end:
pop {r4, r5, r6, r7, r8, r9, r10, r11, pc}
    
