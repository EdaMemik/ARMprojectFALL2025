	// draws a string, (s) and makes sure its will fit in the buffer
	// r0 - x-position
	// r1 - y-position
	// r2 - string (s)
	
	// r9 - CurrChar
	// r10 - temporary value used to get location of current character
	
	// saves all of the inputs
	mov r5, r0
	mov r6, r1
	mov r7, r2
	
	// if the y-position is off of the buffer, the program will end
	cmp r6, #0
	blt end
	cmp r6, #59
	bgt end
	
	lsl r6, #7
	
	mov r3, #0
	mov r9, #0
	mov r10, #0
	
	b test_letter
	body_print:
	
		//this gets a single letter from the string, then takes the base
		//adress for the character buffer and uses the or statment to append
		//the x and the y coordinates. The y value was shifted 7 to the left
		// in order for this to work.
		ldrb r9, [r7, r3]
		ldr r10, =0xc9000000
		orr r10, r5
		orr r10, r6
		strb r9, [r10] 	
		//the x cordinate is indexed to the right one, and the position the
		//byte taken from the string is also indexed by one
		add r5, r5, #1
		add r3, r3, #1	
