// These are addresses for the pixel buffer and text buffer
.EQU PIX_BUFFER, 0xc8000000
.EQU TEXT_BUFFER, 0xc9000000

// These are some useful defines that will help you access structure fields

.EQU num_lvls_passed, 2

.EQU x_pos, 0
.EQU y_pos, 2

.EQU PIXMAP_WIDTH, 4
.EQU PIXMAP_HEIGHT, 6
.EQU PIXMAP_TRANSPARENCY, 8

.EQU x_DIR, 10
.EQU y_DIR, 12

.EQU PIXMAP_ACTIVE, 14
.EQU PIXMAP_VEL_or_FRAME, 16

.EQU PIXMAP_PIXELDATA, 18


.global _start
_start:
	
	// Inital stack
	mov sp, #0x800000
	
	ldr r0, =SimplePix
	mov r1, #50
	mov r2, #150
	strb r1, [r0, #x_pos]
	strb r2, [r0, #y_pos]
	
	bl ClearTextBuffer
//Eda Memik,  2/19/2026	
	

	
inf_loop:	

b end_game_cond_met
continue_game:


//these lines determine if the player is moving and where, 
//then it prints it and checks to see if the player object is touching the side of the screen
ldr r0, =SimplePix
bl moving
.ltorg
ldr r0, =#SimplePix
bl Anim_char_bird
ldr r0, =#SimplePix
bl player_pass_or_nah

//These check to see if any of the obsticles collided with the player object
ldr r0, =#Simpleobs
bl test_static_col
ldr r0, =#Simpleobstwo
bl test_static_col
.ltorg
ldr r0, =#Simpleobsthree
bl test_static_col
ldr r0, =#trackingObsone
bl test_static_col
ldr r0, =#track_obs_2
bl test_static_col
ldr r0, =#track_obs_3
bl test_static_col
.ltorg
ldr r0, =#Sideobsone
bl test_static_col
ldr r0, =#Sideobstwo
bl test_static_col
ldr r0, =#Sideobsthree
bl test_static_col

//this clears the screen and all the objects on it
mov r0, #0xafff
bl ClearVGA	


//thse print the objects onto the screen visually
ldr r0, =#Simpleobs
bl print_obs
ldr r0, =#Simpleobstwo
bl print_obs
ldr r0, =#Simpleobsthree
bl print_obs
.ltorg
ldr r0, =#trackingObsone
bl print_obs
ldr r0, =#track_obs_2
bl print_obs
ldr r0, =#track_obs_3
bl print_obs
ldr r0, =#Sideobsone
bl print_obs
.ltorg
ldr r0, =#Sideobstwo
bl print_obs
ldr r0, =#Sideobsthree
bl print_obs

//these lines determine the behaviors of the obsticles
ldr r0, =#Simpleobs
bl move_obs_grav
ldr r0, =#Simpleobstwo
bl move_obs_grav
.ltorg
ldr r0, =#Simpleobsthree
bl move_obs_grav
ldr r0, =#trackingObsone
bl move_obs_tracking
ldr r0, =#track_obs_2
bl move_obs_tracking
ldr r0, =#track_obs_3
bl move_obs_tracking
.ltorg
ldr r0, =#Sideobsone
bl move_obs_bounce_side
ldr r0, =#Sideobstwo
bl move_obs_bounce_side
ldr r0, =#Sideobsthree
bl move_obs_bounce_side

//this checks to see what level of the game we are on to determine which enemies 
//are spawned in
ldr r0, =#the_game_ended
bl Enemy_Spawn_lvl

//these lines controll the backround
bl cloud_backr
bl cloud_backr_two
bl cloud_backr_three

.ltorg
	b inf_loop


