// in this game you are a bird and you must make it to the right isde of the screen five times to win. there are obsticles in your way.
// I added, gravity, scrolling backround, animated sprite with more than three frames
// the 0 button makes the bird go left, 1 mades it go down, 2 makes it go backwards, 3 makes it go up

